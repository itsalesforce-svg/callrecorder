export interface Product {
  title: string;
  brand?: string;
  price?: string;
  currency?: string;
  description: string;
  features: string[];
  image: string;
  images: string[];
  url: string;
  siteName?: string;
}

export interface AdScene {
  /** What the viewer sees, written as a short on-screen headline. */
  headline: string;
  /** Supporting line under the headline. */
  subline?: string;
  /** Voice-over / narration for the scene. */
  voiceover: string;
  /** Which product image index this scene should use. */
  imageIndex: number;
}

export interface AdCopy {
  hook: string;
  callToAction: string;
  scenes: AdScene[];
  caption: string;
  hashtags: string[];
  /** "ai" when generated by an LLM, "template" for the built-in engine. */
  engine: 'ai' | 'template';
}

export type AspectRatio = '9:16' | '1:1' | '16:9';

export type Step = 'url' | 'product' | 'script' | 'video';

export interface AppState {
  step: Step;
  product: Product | null;
  ad: AdCopy | null;
  aspect: AspectRatio;
  isLoading: boolean;
  loadingMessage: string;
  error: string | null;
}
