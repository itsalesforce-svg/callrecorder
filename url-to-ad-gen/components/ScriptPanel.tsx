'use client';

import { useMemo, useRef, useState } from 'react';
import { useStore } from '@/lib/store';
import { AdPlayer } from '@/components/AdPlayer';
import { RATIOS } from '@/lib/format';
import type { AspectRatio } from '@/lib/types';

const ASPECTS: AspectRatio[] = ['9:16', '1:1', '16:9'];

const PLAYER_BOX: Record<AspectRatio, { width: number; height: number }> = {
  '9:16': { width: 300, height: 540 },
  '1:1': { width: 400, height: 400 },
  '16:9': { width: 560, height: 320 },
};

export function ScriptPanel() {
  const { ad, product, aspect, setAspect, setStep, setLoading, setError, setAd } = useStore();
  const [copied, setCopied] = useState(false);
  const [editMode, setEditMode] = useState(false);
  const adRef = useRef(ad);

  const fullVoiceover = useMemo(() => {
    if (!ad) return '';
    return [
      ad.hook,
      ...ad.scenes.map((scene) => scene.voiceover || scene.headline),
      ad.callToAction,
    ]
      .filter(Boolean)
      .join(' ');
  }, [ad]);

  if (!ad || !product) return null;
  adRef.current = ad;

  const handleRegenerate = async () => {
    setLoading(true, 'Writing a fresh angle…');
    setError(null);
    try {
      const response = await fetch('/api/generate-ad', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ product, aspect }),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data?.error || 'Could not regenerate the copy.');
      setAd(data.ad);
    } catch (error) {
      setError(error instanceof Error ? error.message : 'Something went wrong.');
    } finally {
      setLoading(false);
    }
  };

  const copyCaption = async () => {
    const text = `${ad.caption}\n\n${ad.hashtags.join(' ')}`.trim();
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 1600);
    } catch {
      setError('Clipboard permission was blocked by the browser.');
    }
  };

  const updateScene = (index: number, key: 'headline' | 'subline' | 'voiceover', value: string) => {
    const next = {
      ...ad,
      scenes: ad.scenes.map((scene, i) => (i === index ? { ...scene, [key]: value } : scene)),
    };
    setAd(next);
  };

  return (
    <section className="animate-fade-up grid gap-6 lg:grid-cols-[minmax(0,1fr)_minmax(0,420px)]">
      <div className="card space-y-5 p-6">
        <header className="flex flex-wrap items-center justify-between gap-3">
          <div>
            <h2 className="text-lg font-semibold">Ad copy</h2>
            <p className="text-xs text-muted">
              {ad.engine === 'ai' ? 'Generated with your OpenAI key' : 'Generated by the built-in copywriter engine'} ·{' '}
              {(ad.scenes.length + 2) * 2.6 < 10 ? '9' : '15'}–20s ad
            </p>
          </div>
          <div className="flex gap-2">
            <button type="button" onClick={() => setEditMode((v) => !v)} className="btn btn-ghost !py-1.5 text-xs">
              {editMode ? 'Done editing' : 'Edit copy'}
            </button>
            <button type="button" onClick={handleRegenerate} className="btn btn-ghost !py-1.5 text-xs">
              ↻ Regenerate
            </button>
          </div>
        </header>

        <div className="rounded-xl border border-brand/30 bg-brand/10 p-4">
          <p className="text-[11px] uppercase tracking-[0.18em] text-brand-soft">Hook</p>
          <p className="mt-1 text-lg font-semibold">{ad.hook}</p>
        </div>

        <ol className="space-y-3">
          {ad.scenes.map((scene, index) => (
            <li key={index} className="rounded-xl border border-line bg-black/25 p-4">
              <div className="flex items-center justify-between text-[11px] uppercase tracking-wider text-muted">
                <span>Scene {index + 1}</span>
                <span>Image {scene.imageIndex + 1}</span>
              </div>
              {editMode ? (
                <div className="mt-2 space-y-2">
                  <input
                    className="field !py-2 text-sm"
                    value={scene.headline}
                    onChange={(event) => updateScene(index, 'headline', event.target.value)}
                  />
                  <input
                    className="field !py-2 text-sm"
                    value={scene.subline ?? ''}
                    placeholder="Subline (optional)"
                    onChange={(event) => updateScene(index, 'subline', event.target.value)}
                  />
                  <textarea
                    className="field !py-2 text-sm"
                    rows={2}
                    value={scene.voiceover}
                    onChange={(event) => updateScene(index, 'voiceover', event.target.value)}
                  />
                </div>
              ) : (
                <div className="mt-2 space-y-1">
                  <p className="text-base font-medium">{scene.headline}</p>
                  {scene.subline && <p className="text-sm text-white/70">{scene.subline}</p>}
                  <p className="text-xs italic text-muted">VO: {scene.voiceover}</p>
                </div>
              )}
            </li>
          ))}
        </ol>

        <div className="rounded-xl border border-accent/30 bg-accent/5 p-4">
          <p className="text-[11px] uppercase tracking-[0.18em] text-accent">Call to action</p>
          <p className="mt-1 font-medium">{ad.callToAction}</p>
        </div>

        <div className="space-y-2">
          <div className="flex items-center justify-between">
            <p className="text-xs uppercase tracking-wider text-muted">Social caption</p>
            <button type="button" onClick={copyCaption} className="btn btn-ghost !py-1 !px-2 text-xs">
              {copied ? 'Copied ✓' : 'Copy'}
            </button>
          </div>
          <p className="rounded-lg border border-line bg-black/25 p-3 text-sm text-white/75">{ad.caption}</p>
          <div className="flex flex-wrap gap-1.5">
            {ad.hashtags.map((tag) => (
              <span key={tag} className="rounded-full bg-white/5 px-2.5 py-1 text-xs text-brand-soft">
                {tag}
              </span>
            ))}
          </div>
        </div>

        <details className="rounded-lg border border-line bg-black/20 p-3 text-sm">
          <summary className="cursor-pointer text-white/70">Full voice-over script</summary>
          <p className="mt-2 whitespace-pre-wrap text-white/70">{fullVoiceover}</p>
        </details>
      </div>

      <div className="card space-y-4 p-6">
        <div>
          <h2 className="text-lg font-semibold">Live preview</h2>
          <p className="text-xs text-muted">Plays the real composition that gets exported.</p>
        </div>

        <div className="flex gap-2">
          {ASPECTS.map((option) => (
            <button
              key={option}
              type="button"
              onClick={() => setAspect(option)}
              className={`flex-1 rounded-lg border px-2 py-2 text-xs transition ${
                aspect === option
                  ? 'border-brand/70 bg-brand/15 text-white'
                  : 'border-line text-muted hover:border-white/25'
              }`}
            >
              <span className="block font-semibold">{RATIOS[option].label}</span>
              <span className="block text-[10px] text-muted">{RATIOS[option].hint}</span>
            </button>
          ))}
        </div>

        <AdPlayer
          key={aspect}
          ad={ad}
          product={product}
          aspect={aspect}
          boxWidth={PLAYER_BOX[aspect].width}
          boxHeight={PLAYER_BOX[aspect].height}
        />

        <button type="button" className="btn btn-primary w-full" onClick={() => setStep('video')}>
          Continue to export →
        </button>
      </div>
    </section>
  );
}
